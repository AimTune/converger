defmodule ConvergerWeb.Manage.ChannelController do
  @moduledoc """
  Channel management for the tenant (ADR-0061): `/api/v1/manage/channels`.

  Requires an API key with the `manage` scope. Responses carry an `ETag`;
  `PUT`, `PATCH` and `DELETE` honour `If-Match` (`ConvergerWeb.ETag`). The
  channel secret is generated by the server and returned only by create and
  `rotate_secret`. Pausing and resuming deliveries stays at
  `/api/v1/channels/:id/pause|resume` (also `manage`).
  """
  use ConvergerWeb, :controller
  use OpenApiSpex.ControllerSpecs

  import ConvergerWeb.ApiSchemas

  alias Converger.Channels
  alias Converger.Channels.Channel
  alias ConvergerWeb.{ETag, Plugs.TenantAuth}

  plug TenantAuth, scope: "manage", api_key_only: true

  action_fallback ConvergerWeb.FallbackController

  tags(["Management"])
  security([%{"apiKey" => []}])

  # Fields the API may set; the tenant comes from the key, the secret from
  # rotate_secret, the circuit breaker from the delivery pipeline.
  @writable ~w(name type mode status require_signature config transformations retry_policy rate_limit)

  operation(:index,
    summary: "List channels",
    description: "Not paginated: every channel of the tenant, sorted by name.",
    operation_id: "manageListChannels",
    responses: with_errors(%{200 => json_schema("Channels", ref("ChannelList"))}, [401, 403])
  )

  def index(conn, _params) do
    render(conn, :index, channels: Channels.list_channels_for_tenant(conn.assigns.tenant.id))
  end

  operation(:show,
    summary: "Get a channel",
    operation_id: "manageGetChannel",
    parameters: [id: path_id("Channel id")],
    responses:
      with_errors(%{200 => json_schema("The channel", ref("ChannelResponse"))}, [401, 403, 404])
  )

  def show(conn, %{"id" => id}) do
    with {:ok, channel} <- fetch(conn, id) do
      conn |> ETag.put_etag(channel) |> render(:show, channel: channel)
    end
  end

  operation(:create,
    summary: "Create a channel",
    description:
      "The response is the only one, besides rotate_secret, with the channel `secret`.",
    operation_id: "manageCreateChannel",
    request_body: json_schema("The channel", ref("ChannelRequest")),
    responses:
      with_errors(
        %{201 => json_schema("Created", ref("ChannelWithSecretResponse"))},
        [400, 401, 403, 422]
      )
  )

  def create(conn, %{"channel" => params}) when is_map(params) do
    attrs = params |> Map.take(@writable) |> Map.put("tenant_id", conn.assigns.tenant.id)

    with {:ok, channel} <- Channels.create_channel(attrs, TenantAuth.actor(conn)) do
      conn
      |> put_status(:created)
      |> ETag.put_etag(channel)
      |> render(:show, channel: channel, include_secret: true)
    end
  end

  def create(_conn, _params), do: {:error, "channel object is required"}

  operation(:update,
    summary: "Update a channel",
    description:
      "`config`, when given, replaces the stored config; `[REDACTED]` values keep the stored secret. Honours `If-Match`.",
    operation_id: "manageUpdateChannel",
    parameters: [id: path_id("Channel id")],
    request_body: json_schema("Fields to change", ref("ChannelRequest")),
    responses:
      with_errors(
        %{200 => json_schema("Updated", ref("ChannelResponse"))},
        [400, 401, 403, 404, 412, 422]
      )
  )

  def update(conn, %{"id" => id, "channel" => params}) when is_map(params) do
    with {:ok, channel} <- fetch(conn, id),
         :ok <- ETag.check_if_match(conn, channel),
         attrs = params |> Map.take(@writable) |> restore_redacted_config(channel),
         {:ok, channel} <- Channels.update_channel(channel, attrs, TenantAuth.actor(conn)) do
      conn |> ETag.put_etag(channel) |> render(:show, channel: channel)
    end
  end

  def update(_conn, _params), do: {:error, "channel object is required"}

  operation(:delete,
    summary: "Delete a channel",
    description:
      "Deletes the channel with its conversations; their activities and deliveries are purged in the background. Honours `If-Match`.",
    operation_id: "manageDeleteChannel",
    parameters: [id: path_id("Channel id")],
    responses: with_errors(%{204 => "Deleted"}, [401, 403, 404, 412])
  )

  def delete(conn, %{"id" => id}) do
    with {:ok, channel} <- fetch(conn, id),
         :ok <- ETag.check_if_match(conn, channel),
         {:ok, _} <- Channels.delete_channel(channel, TenantAuth.actor(conn)) do
      send_resp(conn, :no_content, "")
    end
  end

  operation(:rotate_secret,
    summary: "Rotate a channel's secret",
    description:
      "Generates a new channel secret, returned once; the old one stops working at once. Tokens already issued stay valid until they expire or are revoked.",
    operation_id: "manageRotateChannelSecret",
    parameters: [channel_id: path_id("Channel id")],
    responses:
      with_errors(
        %{200 => json_schema("The new secret", ref("ChannelWithSecretResponse"))},
        [401, 403, 404]
      )
  )

  def rotate_secret(conn, %{"channel_id" => id}) do
    with {:ok, channel} <- fetch(conn, id),
         {:ok, channel} <- Channels.rotate_secret(channel, TenantAuth.actor(conn)) do
      conn |> ETag.put_etag(channel) |> render(:show, channel: channel, include_secret: true)
    end
  end

  defp fetch(conn, id) do
    with {:ok, id} <- Ecto.UUID.cast(id),
         %Channel{} = channel <-
           Converger.Repo.get_by(Channel, id: id, tenant_id: conn.assigns.tenant.id) do
      {:ok, channel}
    else
      _ -> {:error, :not_found}
    end
  end

  # A client that read the channel and sends its config back unchanged
  # (Terraform does) must not overwrite the stored secrets with the
  # placeholder: a `[REDACTED]` value keeps the stored one.
  defp restore_redacted_config(%{"config" => config} = attrs, channel) when is_map(config) do
    Map.put(attrs, "config", restore(config, channel.config || %{}))
  end

  defp restore_redacted_config(attrs, _channel), do: attrs

  defp restore(input, stored) when is_map(input) and is_map(stored) do
    Map.new(input, fn {key, value} ->
      stored_value = Map.get(stored, key)

      cond do
        value == Converger.Secrets.redacted() -> {key, stored_value}
        is_map(value) and is_map(stored_value) -> {key, restore(value, stored_value)}
        true -> {key, value}
      end
    end)
  end
end
