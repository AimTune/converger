#!/usr/bin/env bash
# Writes docs/benchmarks/backbone-matrix.md from a backbone matrix report
# (load/report.js --title "Backbone matrix" ... output). Used by
# load/matrix.sh (LOAD_MATRIX_PUBLISH=1) and the nightly Load workflow.
#
# Usage: load/publish_matrix.sh <report.md> [<source note>]
set -euo pipefail

report="$1"
note="${2:-}"
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
page="$ROOT/docs/benchmarks/backbone-matrix.md"

{
  cat <<'HEADER'
---
title: Backbone matrix
description: Load harness results per event backbone (Native, Kafka) and node count (1, 3), regenerated by the nightly Load workflow.
sidebar_position: 2
---

# Backbone matrix

<!-- Generated by load/publish_matrix.sh. Do not edit by hand. -->

How the event backbone ([ADR-0070](../adr/0070-pluggable-event-backbone.md)) changes the numbers of the
[load harness](index.md): every scenario on the Native backbone (Phoenix.PubSub + Oban on Postgres) and on Kafka,
with one and three nodes. The `backbone` rows are the backbone zero-loss check: every activity of the run is
published to the backbone, and a platform webhook subscriber must observe each one exactly once.

HEADER
  if [ -n "$note" ]; then printf '%s\n\n' "$note"; fi
  # The report's own title is replaced by the one above.
  sed '1{/^# /d}' "$report"
} >"$page"

echo "wrote $page"
