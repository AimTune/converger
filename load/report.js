// Renders load harness results as markdown and gates regressions (no
// dependencies, Node >= 22).
//
//   node load/report.js [--baseline <results.json>] [--threshold 0.15]
//                       [--out <file.md>] [--title <text>] <results.json>...
//
// Several results files (one per topology, from load/run.sh) become one
// report. With --baseline, every compared metric gets a before/after column,
// and the exit code is 1 when one regressed by more than --threshold
// (default 15 %) or when any run failed a check (lost acked messages, k6
// thresholds). A regression needs both the relative change and an absolute
// one above the metric's noise floor, so 4 ms -> 5 ms is not a 25 % regression.
"use strict";

const fs = require("node:fs");

// [scenario, label, path into the scenario, better ("lower" | "higher"),
//  noise floor, compared against the baseline]
const METRICS = [
  ["e2e", "REST→WS p50 (ms)", "e2e_latency_ms.p50", "lower", 5, false],
  ["e2e", "REST→WS p95 (ms)", "e2e_latency_ms.p95", "lower", 5, true],
  ["e2e", "REST→WS p99 (ms)", "e2e_latency_ms.p99", "lower", 5, false],
  ["e2e", "REST POST p95 (ms)", "rest_latency_ms.p95", "lower", 5, true],
  ["e2e", "sustained msgs/s (acked)", "msgs_per_s", "higher", 2, false],
  ["e2e", "WS frames/s delivered", "frames_per_s", "higher", 10, false],
  ["e2e", "WS connections", "ws_connections", null, 0, false],
  ["webhook_burst", "inbound accepted/s", "inbound_per_s", "higher", 5, false],
  ["webhook_burst", "inbound POST p95 (ms)", "inbound_latency_ms.p95", "lower", 5, true],
  ["webhook_burst", "inbound→provider p50 (ms)", "delivery_latency_ms.p50", "lower", 10, false],
  ["webhook_burst", "inbound→provider p95 (ms)", "delivery_latency_ms.p95", "lower", 10, true],
  ["webhook_burst", "inbound→provider p99 (ms)", "delivery_latency_ms.p99", "lower", 10, false],
  ["webhook_burst", "deliveries/s", "deliveries_per_s", "higher", 5, false],
  ["webhook_burst", "queue drained after burst (s)", "drain_after_burst_s", "lower", 2, false],
  ["idle", "idle sockets connected", "ws_connections", null, 0, false],
  ["idle", "connect p95 (ms)", "ws_connect_ms.p95", "lower", 5, false],
  ["idle", "memory per idle socket (KiB)", "kib_per_socket", "lower", 2, true],
  ["reconnect_storm", "reconnect p95 (ms)", "ws_reconnect_ms.p95", "lower", 50, true],
  ["reconnect_storm", "reconnect max (ms)", "ws_reconnect_ms.max", "lower", 100, false],
  ["reconnect_storm", "REST→WS p95 during storms (ms)", "e2e_latency_ms.p95", "lower", 5, false],
  ["rolling_restart", "node back to ready, max (s)", "recovery_max_s", "lower", 2, false],
  ["rolling_restart", "client reconnect max (ms)", "ws_reconnect_ms.max", "lower", 500, false],
  ["node_kill", "killed node back to ready (s)", "recovery_max_s", "lower", 2, false],
  ["node_kill", "client reconnect max (ms)", "ws_reconnect_ms.max", "lower", 500, false],
  ["backbone", "activity events observed / expected", "events_observed", null, 0, false],
  ["backbone", "duplicate events at the subscriber", "duplicate_events", null, 0, false],
  ["backbone", "send→backbone subscriber p50 (ms)", "publish_to_subscriber_ms.p50", "lower", 10, false],
  ["backbone", "send→backbone subscriber p95 (ms)", "publish_to_subscriber_ms.p95", "lower", 10, false],
  ["backbone", "send→backbone subscriber p99 (ms)", "publish_to_subscriber_ms.p99", "lower", 10, false],
  ["backbone", "caught up after the delivery queues drained (s)", "caught_up_after_drain_s", "lower", 2, false],
];

const LOSS = ["e2e", "webhook_burst", "reconnect_storm", "rolling_restart", "node_kill", "backbone"];

const get = (obj, path) => path.split(".").reduce((o, k) => (o === null || o === undefined ? undefined : o[k]), obj);
const fmt = (v) => (v === null || v === undefined ? "–" : typeof v === "number" ? String(Number(v.toFixed(1))) : String(v));
const topology = (r) => `${r.run.nodes} node${r.run.nodes > 1 ? "s" : ""}, ${r.run.backbone}`;
const key = (r) => `${r.run.nodes}:${r.run.backbone}`;

function compare(current, before, better, floor, threshold) {
  if (typeof current !== "number" || typeof before !== "number" || !better) return { text: "", regressed: false };
  const delta = current - before;
  const rel = before === 0 ? 0 : delta / before;
  const worse = better === "lower" ? delta > 0 : delta < 0;
  const regressed = worse && Math.abs(rel) > threshold && Math.abs(delta) > floor;
  const sign = rel > 0 ? "+" : "";
  return { text: `${fmt(before)} (${sign}${(rel * 100).toFixed(0)} %${regressed ? " ⚠" : ""})`, regressed };
}

function render(runs, { baseline = [], threshold = 0.15, title } = {}) {
  const regressions = [];
  const out = [];
  const first = runs[0];

  if (title) out.push(`# ${title}`, "");
  out.push(
    `Commit \`${first.run.commit}\`, ${first.run.date}, profile \`${first.run.profile}\`. ` +
      `Generated by \`load/run.sh\` (see [Benchmarks](index.md)).`,
    "",
  );

  // Main table: one column per topology (+ baseline when given).
  const header = ["Scenario", "Metric"];
  for (const r of runs) {
    header.push(topology(r));
    if (baseline.length) header.push("baseline (Δ)");
  }
  out.push(`| ${header.join(" | ")} |`, `| ${header.map(() => "---").join(" | ")} |`);

  for (const [scenario, label, path, better, floor, gated] of METRICS) {
    if (!runs.some((r) => r.scenarios[scenario])) continue;
    const row = [scenario, label];
    for (const r of runs) {
      const v = get(r.scenarios[scenario], path);
      row.push(fmt(v));
      if (baseline.length) {
        const b = baseline.find((x) => key(x) === key(r));
        const c = compare(v, b && get(b.scenarios[scenario], path), better, floor, threshold);
        row.push(c.text || "–");
        if (gated && c.regressed) regressions.push(`${topology(r)}: ${scenario} ${label} ${c.text}`);
      }
    }
    out.push(`| ${row.join(" | ")} |`);
  }

  for (const scenario of LOSS) {
    if (!runs.some((r) => r.scenarios[scenario])) continue;
    const row = [scenario, "**lost acked messages**"];
    for (const r of runs) {
      row.push(fmt(get(r.scenarios[scenario], "lost_acked_messages")));
      if (baseline.length) row.push("must be 0");
    }
    out.push(`| ${row.join(" | ")} |`);
    // Holes the server could not replay under database pressure (#35) and
    // the client recovered with `sync`: not lost, but worth seeing.
    if (runs.some((r) => get(r.scenarios[scenario], "gaps_resynced"))) {
      const info = [scenario, "holes recovered with `sync` / `replay_unavailable` errors"];
      for (const r of runs) {
        const s = r.scenarios[scenario];
        info.push(`${fmt(get(s, "gaps_resynced"))} / ${fmt(get(s, "replay_unavailable"))}`);
        if (baseline.length) info.push("–");
      }
      out.push(`| ${info.join(" | ")} |`);
    }
  }
  out.push("");

  // Resources per scenario and node.
  out.push("### Resources", "", "Highest values sampled while the scenario ran (CPU and RSS about every 2.5 s, the rest every second).", "");
  out.push("| Topology | Scenario | Node | CPU avg % | CPU max % | RSS max (MiB) | DB pool wait max (ms) | Background pool wait max (ms) | Oban queue depth max |");
  out.push("| --- | --- | --- | --- | --- | --- | --- | --- | --- |");
  for (const r of runs) {
    for (const [scenario, s] of Object.entries(r.scenarios)) {
      const res = s.resources;
      if (!res) continue;
      for (const [node, n] of Object.entries(res.nodes)) {
        out.push(
          `| ${topology(r)} | ${scenario} | ${node} | ${fmt(n.cpu_avg_pct)} | ${fmt(n.cpu_max_pct)} | ${fmt(n.rss_max_mib)} | ` +
            `${node === "db" || node === "kafka" ? "–" : fmt(res.db_pool_wait_max_ms)} | ${node === "db" || node === "kafka" ? "–" : fmt(res.db_background_pool_wait_max_ms)} | ${node === "db" || node === "kafka" ? "–" : fmt(res.oban_depth_max)} |`,
        );
      }
    }
  }
  out.push("");

  // Parameters and hardware, so numbers are comparable between runs.
  out.push("### Setup", "");
  for (const r of runs) {
    const h = r.hardware;
    out.push(
      `- **${topology(r)}**: ${h.docker_cpus} vCPU and ${fmt(h.docker_memory_bytes / 1024 ** 3)} GiB visible to Docker ` +
        `(${h.runner_os}, ${h.runner}, kernel ${h.kernel}, Docker ${h.docker_version}); ` +
        `per-node limits CPU ${h.app_cpus_limit}, memory ${h.app_memory_limit}; Postgres ${h.postgres_version}, ` +
        `${fmt(h.database_size_bytes / 1024 ** 2)} MiB after the run; pool size ${h.pool_size}${h.background_pool_size !== undefined ? ` + ${h.background_pool_size} background` : ""}; mock provider latency ` +
        `${r.mock ? `${r.mock.latencyMs}+${r.mock.jitterMs} ms, error rate ${r.mock.errorRate}` : "–"}.`,
    );
    for (const [scenario, s] of Object.entries(r.scenarios)) {
      out.push(`  - \`${scenario}\`: ${Object.entries(s.params || {}).map(([k, v]) => `${k}=${v}`).join(", ")}`);
    }
  }
  out.push("");

  out.push("### Checks", "");
  for (const r of runs) {
    for (const c of r.checks) out.push(`- ${c.ok ? "✅" : c.warning ? "⚠️" : "❌"} ${topology(r)}: ${c.name} (${c.detail})`);
  }
  if (baseline.length) {
    out.push(
      regressions.length
        ? `- ❌ p95 regressions beyond ${threshold * 100} %: ${regressions.join("; ")}`
        : `- ✅ no gated metric regressed beyond ${threshold * 100} % against the baseline`,
    );
  }
  out.push("");

  return { markdown: out.join("\n"), regressions };
}

module.exports = { render, METRICS };

if (require.main === module) {
  const args = process.argv.slice(2);
  const opts = { baseline: [], threshold: 0.15 };
  const files = [];
  let outFile = null;
  for (let i = 0; i < args.length; i++) {
    const a = args[i];
    if (a === "--baseline") opts.baseline.push(JSON.parse(fs.readFileSync(args[++i], "utf8")));
    else if (a === "--threshold") opts.threshold = Number(args[++i]);
    else if (a === "--out") outFile = args[++i];
    else if (a === "--title") opts.title = args[++i];
    else files.push(a);
  }
  if (files.length === 0) {
    console.error("usage: node load/report.js [--baseline results.json] [--threshold 0.15] [--out file.md] [--title t] results.json...");
    process.exit(2);
  }
  const runs = files.map((f) => JSON.parse(fs.readFileSync(f, "utf8")));
  const { markdown, regressions } = render(runs, opts);
  if (outFile) fs.writeFileSync(outFile, markdown + "\n");
  else console.log(markdown);

  const failed = runs.filter((r) => !r.ok);
  if (failed.length) console.error(`checks failed for: ${failed.map(topology).join(", ")}`);
  if (regressions.length) console.error(`regressions: ${regressions.join("; ")}`);
  process.exit(failed.length || regressions.length ? 1 : 0);
}
