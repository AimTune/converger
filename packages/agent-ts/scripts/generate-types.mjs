#!/usr/bin/env node
// Generates src/generated/protocol.ts from the Converger Protocol v1 JSON
// Schemas (priv/protocol/v1 of this repository, published under
// https://converger.aimtune.dev/schemas/protocol/v1/): the message data types
// (messages/*.schema.json), the server frames (frames/server/*), the client and
// agent frames (frames/client/*, frames/channel/*) and the shared definitions
// (common.schema.json#/$defs). src/frames.ts re-exports them under the SDK's
// public names.
//
//   pnpm run generate:types           write src/generated/protocol.ts
//   pnpm run generate:types --check   fail when the committed file is stale (CI)
//
// Every `$ref` in the schemas is relative; a `$ref` (or `$id`) under the
// published base URL is read from priv/protocol/v1 as well, never fetched.

import { readFileSync, readdirSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join, relative, resolve, sep } from "node:path";
import { fileURLToPath } from "node:url";
import { compile } from "json-schema-to-typescript";

const BASE_URL = "https://converger.aimtune.dev/schemas/protocol/v1/";

const here = dirname(fileURLToPath(import.meta.url));
const packageDir = resolve(here, "..");
const schemaDir = resolve(packageDir, "../../priv/protocol/v1");
const outFile = join(packageDir, "src/generated/protocol.ts");
const check = process.argv.includes("--check");

const pascal = (name) =>
  name
    .replace(/\.schema\.json$/, "")
    .split(/[^A-Za-z0-9]+/)
    .filter(Boolean)
    .map((part) => part[0].toUpperCase() + part.slice(1))
    .join("");

// The TypeScript name of each generated schema file (relative to schemaDir).
function typeName(file) {
  const [group, kind, name] = file.split("/");
  if (group === "messages") return `${pascal(kind)}MessageData`;
  if (group === "frames" && kind === "server") return `Server${pascal(name)}Frame`;
  if (group === "frames" && kind === "client") return `Client${pascal(name)}Frame`;
  if (group === "frames" && kind === "channel") return `Channel${pascal(name)}`;
  return { "server-frame.schema.json": "ServerFrame", "client-frame.schema.json": "ClientFrame", "activity.schema.json": "Activity" }[file];
}

const files = (dir) =>
  readdirSync(join(schemaDir, dir))
    .filter((file) => file.endsWith(".schema.json"))
    .sort()
    .map((file) => `${dir}/${file}`);

const generated = [
  ...files("messages"),
  ...files("frames/server"),
  ...files("frames/client"),
  ...files("frames/channel"),
];

// A schema file with the generator's names: its own title becomes its type
// name, the titles of common.schema.json's $defs their PascalCase key. The
// schema's prose title stays in the description (and so in the doc comment).
function load(file) {
  const schema = JSON.parse(readFileSync(join(schemaDir, file), "utf8"));
  const name = typeName(file);

  if (name) {
    const prose = [schema.title, schema.description].filter(Boolean).join(". ");
    schema.title = name;
    if (prose) schema.description = prose;
  }

  stripRefSiblings(schema);

  // A server frame's inline `data` gets a name of its own (ErrorData, RunData,
  // WelcomeData, ...): the agent frame schema references some of them.
  const data = schema.properties?.data;
  if (file.startsWith("frames/server/") && data && !data.$ref && data.type === "object") {
    data.title = `${pascal(file.split("/")[2])}Data`;
  }
  // Examples are documentation, not types.
  delete schema.examples;

  if (file === "common.schema.json") {
    for (const [key, def] of Object.entries(schema.$defs)) def.title = pascal(key);
  }

  return schema;
}

// `{$ref, description, ...}` would become a copy of the referenced type
// (MessageActions1, ...): keep the reference only.
function stripRefSiblings(node) {
  if (Array.isArray(node)) return node.forEach(stripRefSiblings);
  if (node === null || typeof node !== "object") return;
  if (typeof node.$ref === "string") {
    for (const key of Object.keys(node)) if (key !== "$ref") delete node[key];
    return;
  }
  for (const value of Object.values(node)) stripRefSiblings(value);
}

// A path or URL the ref parser hands us, as a file relative to schemaDir.
function schemaFile(url) {
  if (url.startsWith(BASE_URL)) return url.slice(BASE_URL.length);
  const path = url.startsWith("file:") ? fileURLToPath(url) : url;
  return relative(schemaDir, resolve(path)).split(sep).join("/");
}

const root = {
  title: "ConvergerProtocolV1",
  type: "object",
  additionalProperties: false,
  properties: {},
  $defs: Object.fromEntries(
    generated.map((file) => [typeName(file), { $ref: file }]),
  ),
};

const banner = `/* eslint-disable */
/**
 * GENERATED by scripts/generate-types.mjs from the Converger Protocol v1 JSON
 * Schemas (priv/protocol/v1, ${BASE_URL}). Do not edit:
 * change the schemas and run \`pnpm run generate:types\`.
 *
 * @module
 */`;

let source = await compile(root, "ConvergerProtocolV1", {
  cwd: schemaDir + sep,
  bannerComment: banner,
  unreachableDefinitions: true,
  additionalProperties: true,
  strictIndexSignatures: false,
  unknownAny: true,
  ignoreMinAndMaxItems: true,
  format: true,
  style: { printWidth: 120, singleQuote: false, trailingComma: "all" },
  $refOptions: {
    resolve: {
      http: false,
      file: false,
      converger: {
        order: 1,
        canRead: true,
        read: (file) => JSON.stringify(load(schemaFile(file.url))),
      },
    },
  },
});

// The empty root interface is not useful to SDK users.
source = source
  .replace(/\r\n/g, "\n")
  .replace(/^export interface ConvergerProtocolV1 \{\}\n/m, "")
  // TSDoc has no @minItems / @maxItems tags: keep the bounds as prose.
  .replace(/^(\s*)\* @minItems (\d+)$/gm, "$1* At least $2 items.")
  .replace(/^(\s*)\* @maxItems (\d+)$/gm, "$1* At most $2 items.");

if (check) {
  let current = "";
  try {
    current = readFileSync(outFile, "utf8").replace(/\r\n/g, "\n");
  } catch {
    // missing: stale
  }

  if (current !== source) {
    console.error(
      `${relative(process.cwd(), outFile)} is out of date with priv/protocol/v1: run \`pnpm --filter @converger/agent run generate:types\` and commit the result.`,
    );
    process.exit(1);
  }

  console.log(`${relative(process.cwd(), outFile)} is up to date.`);
} else {
  mkdirSync(dirname(outFile), { recursive: true });
  writeFileSync(outFile, source);
  console.log(`wrote ${relative(process.cwd(), outFile)}`);
}
